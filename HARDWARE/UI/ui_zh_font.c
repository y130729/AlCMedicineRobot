static void UI_ZH_DrawChar(u16 x, u16 y, u8 index, u16 color, u16 back)
{
	u8 row;
	u8 col;
	u16 bits;

	if(index >= (sizeof(zh_bitmap) / sizeof(zh_bitmap[0]))) return;
	for(row = 0; row < 16; row++)
	{
		bits = ((u16)zh_bitmap[index][row * 2] << 8) |
		       zh_bitmap[index][row * 2 + 1];
		for(col = 0; col < 16; col++)
		{
			LCD_Fast_DrawPoint(x + col, y + row,
			                   (bits & (0x8000 >> col)) ? color : back);
		}
	}
}

void UI_ZH_DrawText(u16 x, u16 y, const u8 *text, u16 color, u16 back)
{
	while(*text != ZH_END)
	{
		UI_ZH_DrawChar(x, y, *text, color, back);
		x += 16;
		text++;
	}
}
