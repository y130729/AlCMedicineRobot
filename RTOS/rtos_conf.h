#ifndef __RTOS_CONF_H
#define __RTOS_CONF_H
//////////////////////////////////////////////////////////////////////////////////
// 本文件是 FreeRTOS 移植的总开关配置文件
// 所有模块通过本文件统一判断是否启用 RTOS，避免条件编译散落在各文件
//////////////////////////////////////////////////////////////////////////////////

// RTOS_ENABLE:
//   1 = 启用 FreeRTOS（多任务调度运行）
//   0 = 关闭 FreeRTOS（保持原始裸机 while(1) 大循环）
// 切换后重新编译即可，硬件初始化流程两种模式完全一致。
#define RTOS_ENABLE  1

#endif /* __RTOS_CONF_H */
